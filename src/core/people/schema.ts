/**
 * Database tables for the People area: Members, roles, the allowlist, and
 * later Follow.
 *
 * Each area of `src/core/` keeps its tables in its own `schema.ts`, and
 * `src/db/schema.ts` gathers them all. Drizzle uses them in two ways:
 * - `pnpm db:generate` (drizzle-kit) compares them with the committed
 *   migrations in `src/db/migrations/` and writes a new SQL migration for any
 *   difference.
 * - Operations import these table objects to build type-checked queries
 *   (`db.select().from(allowlistEntry)`).
 *
 * Never edit the database by hand; change a schema file and generate a
 * migration. Only operations (`*.operations.ts`) should query these tables
 * (ADR 0002, ADR 0004).
 */
import {
  bigint,
  boolean,
  index,
  pgTable,
  text,
  timestamp,
} from "drizzle-orm/pg-core";

/**
 * Columns shared by most tables. Each call builds fresh column objects, as
 * Drizzle requires one per table.
 */
function identityId() {
  // ADR 0003: 64-bit integer keys generated by the database.
  return bigint("id", { mode: "number" })
    .primaryKey()
    .generatedAlwaysAsIdentity();
}
function createdAt() {
  return timestamp("created_at", { withTimezone: true }).notNull().defaultNow();
}
function updatedAt() {
  return timestamp("updated_at", { withTimezone: true }).notNull().defaultNow();
}

/**
 * Email addresses allowed to sign up while the site is invite-only.
 * Stored normalised (see `email.ts`); signup checks it.
 */
export const allowlistEntry = pgTable("allowlist_entry", {
  email: text("email").primaryKey(),
  createdAt: createdAt(),
});

// ---------------------------------------------------------------------------
// Members and their logins.
//
// These four tables are the ones Better Auth (src/auth/auth.ts) reads and
// writes. Their columns are fixed by Better Auth: the property names on the
// left (`emailVerified`, `expiresAt`) are what it looks for, mapped through
// the `fields` options in auth.ts where ours differ (its `user` is our
// Member, its `name` our display name, its `userId` our `memberId`). Better
// Auth checks these definitions against its expectations at startup, so an
// upgrade that changes them fails loudly rather than corrupting data.
// Column names in the database are snake_case.
// ---------------------------------------------------------------------------

/** A Member: a person with an account (CONTEXT.md). */
export const member = pgTable("member", {
  id: identityId(),
  /** Public @handle; format rules in handle.ts. Stored lowercased. */
  handle: text("handle").notNull().unique(),
  /** Shown beside the handle. Starts equal to it; editable in ticket 12. */
  displayName: text("display_name").notNull(),
  /** Login address, stored normalised (email.ts). Never shown publicly. */
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").notNull().default(false),
  /** Better Auth's avatar field; unused until profiles (ticket 12). */
  image: text("image"),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

/** Better Auth: one logged-in browser. Deleted on logout or expiry. */
export const session = pgTable(
  "session",
  {
    id: identityId(),
    memberId: bigint("member_id", { mode: "number" })
      .notNull()
      .references(() => member.id, { onDelete: "cascade" }),
    /** The secret sent in the session cookie. */
    token: text("token").notNull().unique(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index("session_member_id_index").on(table.memberId)],
);

/**
 * Better Auth: a way a Member can log in. For email and password there is
 * one row per Member (`providerId` "credential") holding the password hash.
 * The token columns are for third-party sign-in, which we do not use
 * (ADR 0001), but Better Auth requires them.
 */
export const account = pgTable(
  "account",
  {
    id: identityId(),
    memberId: bigint("member_id", { mode: "number" })
      .notNull()
      .references(() => member.id, { onDelete: "cascade" }),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    /** Password hash (scrypt), never the password itself. */
    password: text("password"),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: timestamp("access_token_expires_at", {
      withTimezone: true,
    }),
    refreshTokenExpiresAt: timestamp("refresh_token_expires_at", {
      withTimezone: true,
    }),
    scope: text("scope"),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index("account_member_id_index").on(table.memberId)],
);

/**
 * Better Auth: short-lived tokens, such as for password reset. (Email
 * verification links carry a signed token instead and need no row.)
 */
export const verification = pgTable(
  "verification",
  {
    id: identityId(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index("verification_identifier_index").on(table.identifier)],
);
